-- 20261113100000_lr_card_flags.sql
--
-- WHAT
--   `lr_card_flags` — one row per review/drill card the user has flagged as
--   problematic, with a reason from a fixed list (duplicate, missing_info,
--   unclear, wrong, bad). `item_ref` is the drill id, the same key
--   `lr_attempt_log.item_ref` uses, so authored and synthesized drills flag
--   the same way.
--
-- WHY
--   The review queue kept serving cards the user had already judged broken
--   (duplicates above all). A flag records the judgement once and
--   `fetchReviewQueue` excludes unresolved flags from every future queue.
--   `resolved_at` lets a fixed card re-enter without deleting the audit row.
--
-- SHAPE
--   One active flag per (user_id, item_ref): flagging again replaces the
--   reason (upsert). `concept_id` is denormalised so triage can group flags
--   by concept without resolving drill ids through unit content.
--
-- RLS POSTURE
--   anon_all, matching the rest of the lr_* productivity set (the known
--   permissive posture — see SECURITY_RLS_MIGRATION.md; migrate with them).
--
-- ORDER
--   Additive. Apply before shipping the Nexus Local build whose ReviewSession
--   carries the flag menu; an older build never touches the table.

create table if not exists public.lr_card_flags (
  id          bigint generated by default as identity primary key,
  user_id     text not null default 'default',
  item_ref    text not null,
  concept_id  text,
  reason      text not null check (reason in ('duplicate','missing_info','unclear','wrong','bad')),
  note        text,
  created_at  timestamptz not null default now(),
  resolved_at timestamptz
);

create unique index if not exists lr_card_flags_user_item_key
  on public.lr_card_flags(user_id, item_ref);

alter table public.lr_card_flags enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where tablename = 'lr_card_flags' and policyname = 'anon_all'
  ) then
    create policy anon_all on public.lr_card_flags
      for all using (true) with check (true);
  end if;
end $$;
