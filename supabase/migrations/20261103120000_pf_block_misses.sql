-- 20261103120000_pf_block_misses.sql
--
-- WHAT
--   Adds `pf_block_misses` — one row per scheduled task block the user says
--   they did NOT complete. The counterpart of a `pf_task_sessions` row keyed to
--   a `cal_block_id` (the "worked" tick).
--
-- WHY
--   PathFinder's schedule-adherence stats grade every task-linked calendar
--   block as done / missed / unmarked. "Done" already has a ledger. "Missed"
--   needs its own: a zero-minute session would be read as time worked by every
--   consumer of `pf_task_sessions` (WeekTimeStrip, sessions/time completion
--   modes), so it lives in a separate table that nothing else reads.
--
-- SHAPE
--   Same occurrence key as `pf_task_sessions`: `cal_block_id` may be the
--   NEGATIVE virtual id of a recurring occurrence (recurring_id * 100000 +
--   dayOffset — see expandRecurring), so it is deliberately not a foreign key.
--   The unique index is NOT partial, so PostgREST's `on_conflict=task_id,
--   cal_block_id` can infer it (the trap 20260820150000 fixed for sessions).
--   `minutes` snapshots the block's length at the time it was marked.
--
--   Done and missed are mutually exclusive per occurrence; the client clears
--   one when setting the other. Nothing here enforces that across tables.
--
-- RLS POSTURE
--   Mirrors pf_task_sessions' owner_all — auth.uid(), no anon policy. Misses
--   are personal, so there is no team policy.
--
-- ORDER
--   Additive. Apply before shipping a PathFinder build with the "did not
--   complete" button; an older build never touches the table.

create table if not exists public.pf_block_misses (
  id           bigint generated by default as identity primary key,
  user_id      text    not null default 'default',
  task_id      bigint  not null references public.pf_tasks(id) on delete cascade,
  cal_block_id bigint  not null,
  date         text    not null,
  minutes      integer not null default 0,
  created_at   timestamptz not null default now()
);

create unique index if not exists pf_block_misses_occurrence_key
  on public.pf_block_misses(task_id, cal_block_id);
create index if not exists pf_block_misses_user_date_idx
  on public.pf_block_misses(user_id, date);

alter table public.pf_block_misses enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where tablename = 'pf_block_misses' and policyname = 'owner_all'
  ) then
    create policy owner_all on public.pf_block_misses
      for all
      using (user_id = (select (auth.uid())::text))
      with check (user_id = (select (auth.uid())::text));
  end if;
end $$;
